void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim){
	//ho che il timer ha una frequenza di un 2Hz
	if (htim->Instance == TIM6) {
		if (numeroToggleFinali > 0) {
			HAL_GPIO_TogglePin(GPIOA, LED_Pin);
			numeroToggleFinali--; // Ne abbiamo fatto uno, ne resta uno in meno
		} else {
			HAL_TIM_Base_Stop_IT(&htim6);
			HAL_GPIO_WritePin(GPIOA, LED_Pin, GPIO_PIN_RESET);
			lampeggio = false;
		}
	}
}



void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) {
	static uint32_t last_millis_up = 0;
	static uint32_t last_millis_down = 0;
    uint32_t current_time = HAL_GetTick();
	if(GPIO_Pin ==BTN_UP_Pin){
		if(current_time - last_millis_up < 200 && lampeggio==true) return;
		last_millis_up=current_time;
		start=true;
		startTimer=current_time;

	}
	if (GPIO_Pin == BTN_DOWN_Pin) {
		if (current_time -last_millis_down < 200) return;
		last_millis_down = current_time;
		start = false;
		lampeggio=true;

		uint32_t numeroToggle=(countms/1000)*2;
		numeroToggleFinali=(int)numeroToggle;
		if(numeroToggleFinali>0){
			HAL_TIM_Base_Start_IT(&htim6);
		}else{
			lampeggio=false;
		}

	}

}

